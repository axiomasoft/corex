#!/usr/bin/env python3
"""P03 module map by the D57 layout rules (stdlib; run from the repository root).

Input: the cloud fact scan (`artifacts/P03-design/cloud/{inventory,consumers}.tsv`, `package-shapes.md`), regenerated by
`cloud/scan.py` on the current tree. Output: `artifacts/P03/module-map.tsv` (one row per PHP file of `packages/*/src`
and `products/*/src`: current path/namespace → target path/namespace + rule) and `artifacts/P03/public-by-usage.tsv`
(implementation classes that stay in place because another package or the product uses them, the package's published
`config/*.php` names them, or the glossary names them; P04 replaces the list by #[Api]/#[Spi]). The product keeps its
layout (glossary N8: N1–N7, including N5, do not apply to it).

  python3 p03-module-map.py            write both files, print a summary, exit 1 on target collisions
  python3 p03-module-map.py --check    rebuild in memory, exit 1 if the committed files differ
"""
import collections, csv, os, re, subprocess, sys

PLAN = 'plans/2026.09.27-№1-COREX-KERNEL'
GLOSSARY = f'{PLAN}/research/03-glossary.md'
CLOUD = f'{PLAN}/artifacts/P03-design/cloud'
OUT = f'{PLAN}/artifacts/P03'
CATEGORIES = ('Contracts', 'Data', 'Enums', 'Events', 'Exceptions')
BRIDGES = ('Internal', 'Laravel', 'Testing', 'PHPStan')
ROLE_CATEGORY = {'contract': 'Contracts', 'enum': 'Enums', 'exception': 'Exceptions', 'data': 'Data'}
STAYS = ('provider',)


def read(name):
    return list(csv.DictReader(open(f'{CLOUD}/{name}', encoding='utf-8'), delimiter='\t'))


def shapes():
    """package → {top entry → 'module'|'bucket'|...} from package-shapes.md tables."""
    out, pkg = collections.defaultdict(dict), None
    for line in open(f'{CLOUD}/package-shapes.md', encoding='utf-8'):
        m = re.match(r'^##+\s+`?([\w/.-]+)`?', line)
        if m:
            pkg = m.group(1)
            continue
        cells = [c.strip().strip('`') for c in line.strip().strip('|').split('|')]
        if pkg and len(cells) >= 2 and cells[1] in ('module', 'bucket', 'laravel', 'testing', 'root-file'):
            out[pkg][cells[0].rstrip('/')] = cells[1]
    return out


def main():
    inventory = read('inventory.tsv')
    consumers = collections.defaultdict(set)
    for r in read('consumers.tsv'):
        if not r['consumer_package'].startswith('<'):  # monorepo tests are not package consumers
            consumers[r['symbol']].add(r['consumer_package'])
    shape = shapes()
    config = {p.split('/')[1]: open(p, encoding='utf-8').read() for p in
              subprocess.run(['git', 'ls-files', 'packages/*/config/*.php'], capture_output=True, text=True,
                             check=True).stdout.split()}
    glossary = open(GLOSSARY, encoding='utf-8').read()
    rows, public = [], []
    for r in inventory:
        path, ns, sym, role, pkg = r['path'], r['namespace'], r['symbol'], r['role'], r['package']
        src = path.split('/src/', 1)[0] + '/src/'
        rel = path[len(src):].split('/')
        kernel = pkg == 'axiomasoft/corex'
        fq = f'{ns}\\{sym}' if sym else ns
        users = sorted(c for c in consumers.get(fq, ()) if c != pkg)
        if path.startswith('packages/') and fq in config.get(path.split('/')[1], ''):
            users.append('<config>')
        if f'`{fq}`' in glossary or (kernel and f'`{sym}`' in glossary):  # kernel rows name symbols by basename
            users.append('<glossary>')
        external = bool(users)
        if path.startswith('products/'):
            rows.append({'package': pkg, 'path': path, 'namespace': ns, 'symbol': sym, 'role': role,
                         'target_path': path, 'target_namespace': ns, 'rule': 'product-n8'})
            continue

        def place(prefix, parts):
            """Place a file inside one module whose directory is `prefix` (list of path parts)."""
            head = parts[0] if len(parts) > 1 else None
            if head in CATEGORIES or head in BRIDGES:
                return prefix + parts, 'keep'
            if role in STAYS:
                return prefix + parts, 'provider'
            if role in ROLE_CATEGORY:
                return prefix + [ROLE_CATEGORY[role]] + parts[1:] if head else prefix + [ROLE_CATEGORY[role], parts[0]], \
                    'category:' + ROLE_CATEGORY[role]
            if external:
                # Another package already names this FQCN: P03 does not move it (P04 classifies it #[Api]/#[Spi]).
                public.append((pkg, fq, ','.join(users)))
                return None, 'public-by-usage'
            return prefix + ['Internal'] + parts, 'internal'

        top = rel[0] if len(rel) > 1 else None
        if len(rel) == 1 and (role in STAYS or re.search(r'Module\.php$', rel[0])) and not kernel:
            target, rule = rel, 'root-entry'
        elif kernel:
            # Kernel: every top entry is a module of the closed glossary list; root holds only the provider.
            target, rule = (rel, 'root-entry') if len(rel) == 1 else place([rel[0]], rel[1:])
        elif top is None or top in CATEGORIES or top in BRIDGES:
            target, rule = place([], rel) if top is None else (rel, 'keep')
        elif shape.get(pkg, {}).get(top) == 'module':
            target, rule = place([top], rel[1:])
        else:
            # A package-level bucket (Support, Models, Commands…) dissolves into the package root module.
            target, rule = place([], rel[1:])
            if target and target[0] == 'Internal':
                target = ['Internal', top] + target[1:]  # keep the dissolved bucket as a group inside Internal
                rule = 'internal'
        if target is None:
            target = rel
        new_path = src + '/'.join(target)
        base = ns.split('\\')
        depth = len(rel) - 1
        root = '\\'.join(base[:len(base) - depth]) if depth else ns
        new_ns = '\\'.join([root] + target[:-1]) if len(target) > 1 else root
        rows.append({'package': pkg, 'path': path, 'namespace': ns, 'symbol': sym, 'role': role,
                     'target_path': new_path, 'target_namespace': new_ns, 'rule': rule})
    targets = collections.Counter(r['target_path'] for r in rows)
    collisions = [t for t, n in targets.items() if n > 1]
    text = '\t'.join(rows[0].keys()) + '\n' + ''.join('\t'.join(r.values()) + '\n' for r in sorted(rows, key=lambda r: r['path']))
    pub = 'package\tsymbol\tconsumers\n' + ''.join('\t'.join(p) + '\n' for p in sorted(set(public)))
    if '--check' in sys.argv:
        same = open(f'{OUT}/module-map.tsv', encoding='utf-8').read() == text and \
            open(f'{OUT}/public-by-usage.tsv', encoding='utf-8').read() == pub
        print('module-map ' + ('OK' if same and not collisions else 'STALE'))
        return 0 if same and not collisions else 1
    os.makedirs(OUT, exist_ok=True)
    open(f'{OUT}/module-map.tsv', 'w', encoding='utf-8').write(text)
    open(f'{OUT}/public-by-usage.tsv', 'w', encoding='utf-8').write(pub)
    moved = [r for r in rows if r['target_path'] != r['path']]
    by_rule = collections.Counter(r['rule'] for r in moved)
    by_pkg = collections.Counter(r['package'] for r in moved)
    for c in collisions:
        print('collision', c)
    print(f'module-map: {len(rows)} files, {len(moved)} moves, {len(set(public))} public-by-usage, '
          f'{len(collisions)} collisions; by rule {dict(sorted(by_rule.items()))}')
    print('by package: ' + ', '.join(f'{k.split("/")[-1]} {v}' for k, v in sorted(by_pkg.items())))
    return 1 if collisions else 0


if __name__ == '__main__':
    sys.exit(main())
