<?php

declare(strict_types=1);

use CoreX\Tooling\Rector\Import\SourceSnapshot;
use CoreX\Tooling\Rector\Import\SubsetImporter;

require dirname(__DIR__, 3).'/vendor/autoload.php';
require __DIR__.'/Import/DocumentationVisitor.php';
require __DIR__.'/Import/SourceSnapshot.php';
require __DIR__.'/Import/SubsetImporter.php';

try {
    $source = __DIR__.'/upstream.json';
    $adjustments = __DIR__.'/native-adjustments.json';
    $destination = __DIR__;
    $check = in_array('--check', $argv, true);
    $baseline = in_array('--baseline', $argv, true);

    foreach ($argv as $argument) {
        if (str_starts_with($argument, '--source=')) {
            $source = substr($argument, strlen('--source='));
        }

        if (str_starts_with($argument, '--destination=')) {
            $destination = substr($argument, strlen('--destination='));
        }

        if (str_starts_with($argument, '--adjustments=')) {
            $adjustments = substr($argument, strlen('--adjustments='));
        }
    }

    $snapshot = SourceSnapshot::load($source);
    $importer = new SubsetImporter;
    $outputs = $importer->baseline($snapshot);

    if (! $baseline) {
        $outputs = $importer->adjusted($outputs, $adjustments);
    }

    foreach ($outputs as $path => $code) {
        $target = $destination.'/'.$path;

        if ($check) {
            if (! is_file($target) || file_get_contents($target) !== $code) {
                throw new RuntimeException('Regenerated byte mismatch: '.$path);
            }

            continue;
        }

        if (! is_dir(dirname($target)) && ! mkdir(dirname($target), 0755, true) && ! is_dir(dirname($target))) {
            throw new RuntimeException('Cannot create output directory');
        }

        if (file_put_contents($target, $code) === false) {
            throw new RuntimeException('Cannot write native output: '.$path);
        }
    }

    if ($check) {
        foreach (['Laravel/src', 'Laravel/config'] as $directory) {
            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($destination.'/'.$directory)) as $file) {
                if ($file instanceof SplFileInfo && $file->isFile() && $file->getExtension() === 'php') {
                    $relative = substr($file->getPathname(), strlen($destination) + 1);

                    if (! isset($outputs[$relative])) {
                        throw new RuntimeException('Unexpected native source file: '.$relative);
                    }
                }
            }
        }
    }

    echo 'Native Laravel subset: '.count($snapshot->production).' production files; reproducible bytes verified.'.PHP_EOL;
} catch (Throwable $exception) {
    fwrite(STDERR, $exception->getMessage().PHP_EOL);
    exit(1);
}
