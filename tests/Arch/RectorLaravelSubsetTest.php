<?php

declare(strict_types=1);

use Illuminate\Support\Facades\Request;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\Process\Process;

it('reproduces the maintained native subset and rejects changed inputs, source bytes and missing closure', function (): void {
    $root = dirname(__DIR__, 2);
    $tooling = $root.'/scripts/quality/rector';
    $files = new Filesystem;
    $directory = sys_get_temp_dir().'/corex-rector-integrity-'.bin2hex(random_bytes(8));
    $files->mkdir($directory);
    $run = static function (array $arguments = []) use ($root, $tooling): Process {
        $process = new Process([PHP_BINARY, $tooling.'/import.php', '--check', ...$arguments], $root);
        $process->setTimeout(30);
        $process->run();

        return $process;
    };

    try {
        $green = $run();
        expect($green->getExitCode())->toBe(0)
            ->and($green->getOutput())->toContain('46 production files');
        $source = json_decode(file_get_contents($tooling.'/upstream.json'), true, flags: JSON_THROW_ON_ERROR);
        expect($source['commit'])->toBe('c0f9a2ff7365cec45d4dc64223608e7cec74604a')
            ->and($source['repository'])->toBe('https://github.com/driftingly/rector-laravel')
            ->and(count($source['production']))->toBe(46)
            ->and(count($source['stubs']))->toBe(79);

        $changed = $source;
        $changed['files'][$source['production'][0]]['text'] .= "\n";
        $files->dumpFile($directory.'/changed.json', json_encode($changed, JSON_THROW_ON_ERROR));
        $red = $run(['--source='.$directory.'/changed.json']);
        expect($red->getExitCode())->toBe(1)
            ->and($red->getErrorOutput())->toContain('Pinned input hash mismatch');

        $incomplete = $source;
        $position = array_search('src/AbstractRector.php', $source['production'], true);
        expect($position)->not->toBeFalse();
        $incomplete['production'][$position] = $source['stubs'][0];
        $files->dumpFile($directory.'/incomplete.json', json_encode($incomplete, JSON_THROW_ON_ERROR));
        $red = $run(['--source='.$directory.'/incomplete.json']);
        expect($red->getExitCode())->toBe(1)
            ->and($red->getErrorOutput())->toContain('Missing native dependency closure');

        $files->mirror($tooling.'/Laravel', $directory.'/Laravel');
        $path = $directory.'/Laravel/src/Rector/FuncCall/AppToResolveRector.php';
        $original = file_get_contents($path);
        $files->dumpFile($path, $original."\n");
        $red = $run(['--destination='.$directory]);
        expect($red->getExitCode())->toBe(1)
            ->and($red->getErrorOutput())->toContain('Regenerated byte mismatch');
        $files->dumpFile($path, $original);
        $files->dumpFile($directory.'/Laravel/src/UntrackedRule.php', '<?php');
        $red = $run(['--destination='.$directory]);
        expect($red->getExitCode())->toBe(1)
            ->and($red->getErrorOutput())->toContain('Unexpected native source file');

        $baseline = new Process([PHP_BINARY, $tooling.'/import.php', '--baseline', '--destination='.$directory.'/baseline'], $root);
        $baseline->run();
        expect($baseline->getExitCode())->toBe(0);
        $adjustments = json_decode(file_get_contents($tooling.'/native-adjustments.json'), true, flags: JSON_THROW_ON_ERROR);
        $relative = 'Laravel/src/Rector/FuncCall/AppToResolveRector.php';
        $annotation = "\n// @phpstan-ignore-next-line\n";
        array_unshift($adjustments[$relative]['edits'], ['offset' => strlen(file_get_contents($directory.'/baseline/'.$relative)), 'delete' => '', 'insert' => $annotation]);
        $adjustments[$relative]['output_sha256'] = hash('sha256', file_get_contents($tooling.'/'.$relative).$annotation);
        $files->dumpFile($directory.'/suppression.json', json_encode($adjustments, JSON_THROW_ON_ERROR));
        $red = $run(['--adjustments='.$directory.'/suppression.json']);
        expect($red->getExitCode())->toBe(1)
            ->and($red->getErrorOutput())->toContain('Static analysis suppression in native output');
    } finally {
        $files->remove($directory);
    }
});

it('executes every pinned upstream fixture and preservation-policy controls with isolated stubs', function (): void {
    $root = dirname(__DIR__, 2);
    $request = new ReflectionClass(Request::class)->getFileName();
    $process = new Process([PHP_BINARY, $root.'/tests/Tooling/Rector/run.php'], $root);
    $process->setTimeout(300);
    $process->run();
    expect($process->getExitCode())->toBe(0, $process->getOutput().$process->getErrorOutput())
        ->and($process->getOutput())->toContain('173 unique fixtures, 36 rule test classes')
        ->and($process->getOutput())->toContain('stubs confined to child process')
        ->and(new ReflectionClass(Request::class)->getFileName())->toBe($request);

    $manifest = json_decode(file_get_contents($root.'/composer.json'), true, flags: JSON_THROW_ON_ERROR);
    $lock = json_decode(file_get_contents($root.'/composer.lock'), true, flags: JSON_THROW_ON_ERROR);
    $dependencies = array_column([...$lock['packages'], ...$lock['packages-dev']], 'name');
    expect($dependencies)->not->toContain('driftingly/rector-laravel', 'symplify/rule-doc-generator-contracts')
        ->and($manifest['require-dev'])->toHaveKey('webmozart/assert')
        ->and(rtrim($manifest['autoload-dev']['psr-4']['CoreX\\Tooling\\Rector\\Laravel\\'], '/'))->toBe('scripts/quality/rector/Laravel/src');
});
